package ai.openpush.gradle.setup

/**
 * The manifest the plugin merges into every variant from the stored choices and `openpush.properties`,
 * so the developer's own `AndroidManifest.xml` is never edited. It is merged above the app's manifest
 * and every library's, so its `tools:node="remove"` entries reach merged services from dependencies.
 */
internal data class ManifestFragment(
    /** `android:value` meta-data, by name. */
    val values: Map<String, String>,
    /** `android:resource` meta-data, by name, as a resource reference such as `@drawable/ic_stat_x`. */
    val resources: Map<String, String>,
    /** Services removed from the merged manifest. */
    val removedServices: List<String>,
    /** Manifest placeholders the fragment's values refer to. */
    val placeholders: Map<String, String>,
) {
    fun xml(): String = buildString {
        append("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n")
        append("<!-- Generated by ai.openpush.setup from ${SetupFile.NAME} and ${OpenPushProperties.NAME}. -->\n")
        append("<manifest xmlns:android=\"$ANDROID\"\n    xmlns:tools=\"$TOOLS\">\n")
        append("    <application>\n")
        values.forEach { (name, value) -> metaData(name, "android:value", value) }
        resources.forEach { (name, value) -> metaData(name, "android:resource", value) }
        removedServices.forEach { append("        <service android:name=\"${escape(it)}\" tools:node=\"remove\" />\n") }
        append("    </application>\n")
        append("</manifest>\n")
    }

    private fun StringBuilder.metaData(name: String, attribute: String, value: String) {
        append("        <meta-data\n")
        append("            android:name=\"${escape(name)}\"\n")
        append("            $attribute=\"${escape(value)}\"\n")
        append("            tools:replace=\"$attribute\" />\n")
    }

    companion object {
        private const val ANDROID = "http://schemas.android.com/apk/res/android"
        private const val TOOLS = "http://schemas.android.com/tools"
        const val APP_ID_PLACEHOLDER = "openpushAppId"
        const val SDK_KEY_PLACEHOLDER = "openpushSdkKey"
        const val META_APP_ID = "ai.openpush.app_id"
        const val META_SDK_KEY = "ai.openpush.sdk_key"
        const val META_ICON = "ai.openpush.notification_icon"
        const val META_CHANNEL = "ai.openpush.notification_channel_id"

        /** A stored icon is a full reference (`@mipmap/ic_launcher`); a bare name is a drawable. */
        private fun resourceReference(icon: String) = if (icon.startsWith("@")) icon else "@drawable/$icon"

        private fun escape(text: String) =
            text.replace("&", "&amp;").replace("\"", "&quot;").replace("<", "&lt;").replace(">", "&gt;")

        @Suppress("UNCHECKED_CAST")
        fun from(choices: Map<String, Map<String, Any?>>, properties: OpenPushProperties): ManifestFragment {
            val values = linkedMapOf<String, String>()
            val resources = linkedMapOf<String, String>()
            val removed = mutableListOf<String>()
            val placeholders = linkedMapOf<String, String>()

            properties.appId?.let {
                placeholders[APP_ID_PLACEHOLDER] = it
                values[META_APP_ID] = "\${$APP_ID_PLACEHOLDER}"
            }
            properties.sdkKey?.let {
                placeholders[SDK_KEY_PLACEHOLDER] = it
                values[META_SDK_KEY] = "\${$SDK_KEY_PLACEHOLDER}"
            }

            if (SetupFile.choiceMode(choices, SetupFile.FIREBASE) == "new") properties.firebase?.let(values::putAll)

            val delivery = choices[SetupFile.ANDROID_DELIVERY]
            val mode = SetupFile.choiceMode(choices, SetupFile.ANDROID_DELIVERY)
            if (mode == "forward" || mode == "automatic") {
                values[PushPlumbingScanner.OPENPUSH_DELIVERY_META] = mode
                (delivery?.get("remove") as? List<String>).orEmpty()
                    .filter { it != PushPlumbingScanner.OPENPUSH_SERVICE && it != delivery?.get("service") }
                    .forEach(removed::add)
            }

            val icons = choices[SetupFile.ICONS]
            if (SetupFile.choiceMode(choices, SetupFile.ICONS) == "reuse") {
                (icons?.get("small") as? String)?.let { resources[META_ICON] = resourceReference(it) }
                (icons?.get("large") as? String)?.let { resources[META_LARGE_ICON] = resourceReference(it) }
                (icons?.get("channel") as? String)?.let { values[META_CHANNEL] = it }
            }
            return ManifestFragment(values, resources, removed, placeholders)
        }

        private const val META_LARGE_ICON = "ai.openpush.notification_large_icon"
    }
}
